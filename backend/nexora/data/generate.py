"""Synthetic enterprise dataset for NEXORA.

Simulates 21 months (Jan 2025 - Sep 2026) of a fictional industrial manufacturer,
"Veltrix Industries", selling 9 products across 4 regions and 3 channels.

The data is generated by a mechanistic simulation (demand -> inventory -> fulfilment),
not by painting numbers on a chart. Two hidden incidents are planted in Q3 2026:

1. Supplier disruption: Kestrel Components' shipments to the North and West
   distribution centres slip from ~1.5 days late to ~11 days late (and arrive
   partially filled) from mid-June 2026. Sensor inventory runs dry -> stockouts
   -> lost sales.
2. Platform incident: order-service degrades between 4 and 22 Aug 2026
   (p95 latency and error rate spike), so a share of online orders never land.

Plus one weak "red herring": overall market demand softens by ~3% in Q3.

The investigation engine is never told any of this. It has to find it.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

SEED = 42
START = "2025-01-01"
END = "2026-09-30"

RAW_DIR = Path(__file__).resolve().parent / "raw"
DOCS_DIR = Path(__file__).resolve().parent / "documents"


@dataclass(frozen=True)
class Product:
    sku: str
    name: str
    category: str
    supplier: str
    price: float  # INR
    base_units: float  # daily units across all regions/channels (2026 level)


PRODUCTS = [
    Product("SNS-100", "Pressure Sensor 100", "Industrial Sensors", "Kestrel Components", 12500, 80),
    Product("SNS-220", "Flow Sensor 220", "Industrial Sensors", "Kestrel Components", 18900, 58),
    Product("MC-40", "Motor Controller 40", "Motor Controllers", "Orion Electronics", 8400, 60),
    Product("MC-75", "Motor Controller 75", "Motor Controllers", "Orion Electronics", 14200, 49),
    Product("HV-10", "Hydraulic Valve 10", "Hydraulic Valves", "Baltic Precision", 3600, 70),
    Product("HV-30", "Hydraulic Valve 30", "Hydraulic Valves", "Baltic Precision", 6900, 51),
    Product("CP-500", "Control Panel 500", "Control Panels", "Orion Electronics", 42000, 17),
    Product("SF-01", "Safety Relay 01", "Safety Equipment", "Meridian Safety", 1250, 120),
    Product("SF-02", "Safety Interlock 02", "Safety Equipment", "Meridian Safety", 2900, 86),
]

REGIONS = {"North": 0.30, "West": 0.28, "South": 0.22, "East": 0.20}
CHANNELS = {"Online": 0.30, "Distributor": 0.45, "Direct Sales": 0.25}
DOW = np.array([1.10, 1.10, 1.10, 1.10, 1.10, 0.75, 0.50])  # Mon..Sun
DOW = DOW / DOW.mean()

SUPPLIER_INCIDENT_START = pd.Timestamp("2026-06-15")
SUPPLIER_INCIDENT_REGIONS = {"North", "West"}
API_INCIDENT = (pd.Timestamp("2026-08-04"), pd.Timestamp("2026-08-22"))
API_ONLINE_LOSS = 0.40
MARKET_SOFTENING_START = pd.Timestamp("2026-07-01")

BASE_LEAD_DAYS = 6
TARGET_DAYS = 18


def _market_index(dates: pd.DatetimeIndex, rng: np.random.Generator) -> np.ndarray:
    idx = np.ones(len(dates))
    soft = dates >= MARKET_SOFTENING_START
    ramp = np.clip((dates[soft] - MARKET_SOFTENING_START).days / 30.0, 0, 1)
    idx[soft] -= 0.03 * ramp
    idx += rng.normal(0, 0.012, len(dates))
    return idx


def _demand_multiplier(dates: pd.DatetimeIndex, market: np.ndarray) -> np.ndarray:
    doy = dates.day_of_year.values
    season = 1 + 0.05 * np.sin(2 * np.pi * (doy - 80) / 365.25)
    months = (dates - pd.Timestamp(START)).days / 30.44
    trend = 0.88 + 0.0065 * months  # ~8% annual growth, ends near 1.0 in mid-2026
    return season * trend * DOW[dates.day_of_week.values] * market


def _supplier_delay(supplier: str, region: str, order_date: pd.Timestamp, rng) -> tuple[float, float]:
    """Return (delay_days, fill_rate) for a replenishment order."""
    if (
        supplier == "Kestrel Components"
        and region in SUPPLIER_INCIDENT_REGIONS
        and order_date >= SUPPLIER_INCIDENT_START - pd.Timedelta(days=10)
    ):
        ramp = np.clip((order_date - (SUPPLIER_INCIDENT_START - pd.Timedelta(days=10))).days / 20, 0, 1)
        delay = max(0.0, rng.normal(0.8 + 12.0 * ramp, 2.5))
        fill = float(np.clip(rng.normal(1 - 0.45 * ramp, 0.06), 0.35, 1.0))
        return round(delay), fill
    base = {"Kestrel Components": 0.8, "Orion Electronics": 0.7, "Baltic Precision": 1.0, "Meridian Safety": 0.5}[supplier]
    return round(max(0.0, rng.normal(base, 0.9))), float(np.clip(rng.normal(0.99, 0.02), 0.9, 1.0))


def generate(seed: int = SEED) -> dict[str, pd.DataFrame]:
    rng = np.random.default_rng(seed)
    dates = pd.date_range(START, END, freq="D")
    n = len(dates)
    market = _market_index(dates, rng)
    mult = _demand_multiplier(dates, market)
    api_down = (dates >= API_INCIDENT[0]) & (dates <= API_INCIDENT[1])

    sales_rows, inv_rows, ship_rows = [], [], []
    ship_id = 1000

    for p in PRODUCTS:
        for region, rw in REGIONS.items():
            mean_daily = p.base_units * rw
            stock = TARGET_DAYS * mean_daily
            pipeline: list[tuple[int, float, dict]] = []  # (arrival_index, qty, record)
            demand_hist: list[float] = []

            for i, d in enumerate(dates):
                # 1. receive shipments
                arriving = [x for x in pipeline if x[0] == i]
                for _, qty, rec in arriving:
                    stock += qty
                    ship_rows.append(rec)
                pipeline = [x for x in pipeline if x[0] != i]

                # 2. weekly replenishment on Mondays
                if d.day_of_week == 0:
                    avg = np.mean(demand_hist[-28:]) if demand_hist else mean_daily
                    in_transit = sum(q for _, q, _ in pipeline)
                    order_qty = max(0.0, TARGET_DAYS * avg - stock - in_transit)
                    if order_qty > 0:
                        delay, fill = _supplier_delay(p.supplier, region, d, rng)
                        lead = BASE_LEAD_DAYS + delay
                        delivered = round(order_qty * fill)
                        ship_id += 1
                        rec = {
                            "shipment_id": f"SHP-{ship_id}",
                            "supplier": p.supplier,
                            "product": p.sku,
                            "region": region,
                            "order_date": d.date().isoformat(),
                            "expected_date": (d + pd.Timedelta(days=BASE_LEAD_DAYS)).date().isoformat(),
                            "delivered_date": (d + pd.Timedelta(days=lead)).date().isoformat(),
                            "delay_days": int(delay),
                            "qty_ordered": int(round(order_qty)),
                            "qty_delivered": int(delivered),
                        }
                        if i + lead < n:
                            pipeline.append((i + lead, delivered, rec))

                # 3. demand by channel
                lam = {c: mean_daily * mult[i] * cw for c, cw in CHANNELS.items()}
                if api_down[i]:
                    lam["Online"] *= 1 - API_ONLINE_LOSS
                demand = {c: rng.poisson(max(l, 0)) for c, l in lam.items()}
                total_demand = sum(demand.values())
                demand_hist.append(total_demand)

                # 4. fulfil from stock (pro-rata across channels when short)
                fulfil_ratio = 1.0 if total_demand == 0 else min(1.0, stock / total_demand)
                fulfilled_total = 0
                for c, dem in demand.items():
                    units = int(np.floor(dem * fulfil_ratio))
                    fulfilled_total += units
                    price = p.price * (1.03 if d >= pd.Timestamp("2026-01-01") else 1.0)
                    price *= rng.normal(1.0, 0.01)
                    sales_rows.append((d, region, c, p.category, p.sku, p.supplier, units, round(price, 2)))
                stock = max(0.0, stock - fulfilled_total)

                inv_rows.append(
                    (d, region, p.sku, round(stock), int(fulfil_ratio < 0.98), total_demand, fulfilled_total)
                )

    sales = pd.DataFrame(
        sales_rows, columns=["date", "region", "channel", "category", "product", "supplier", "units", "unit_price"]
    )
    sales["revenue"] = (sales["units"] * sales["unit_price"]).round(2)
    inventory = pd.DataFrame(
        inv_rows, columns=["date", "region", "product", "stock_on_hand", "stockout", "demand_units", "fulfilled_units"]
    )
    shipments = pd.DataFrame(ship_rows).sort_values("order_date").reset_index(drop=True)

    # service metrics
    services = {
        "order-service": (380, 0.004, 52000),
        "payment-service": (240, 0.002, 31000),
        "catalog-service": (120, 0.001, 140000),
        "inventory-service": (180, 0.002, 64000),
    }
    svc_rows = []
    for s, (lat, err, req) in services.items():
        for i, d in enumerate(dates):
            l = lat * rng.lognormal(0, 0.08)
            e = max(0.0, err * rng.lognormal(0, 0.25))
            r = req * mult[i] * rng.normal(1, 0.03)
            if s == "order-service" and api_down[i]:
                l = rng.normal(2400, 250)
                e = rng.normal(0.065, 0.008)
            if s == "catalog-service" and d == pd.Timestamp("2025-03-12"):
                l, e = 900, 0.03  # an old, unrelated blip
            svc_rows.append((d, s, round(l, 1), round(e, 5), int(r)))
    service_metrics = pd.DataFrame(svc_rows, columns=["date", "service", "p95_latency_ms", "error_rate", "requests"])

    market_df = pd.DataFrame({"date": dates, "demand_index": np.round(market * 100, 2)})

    products_df = pd.DataFrame([p.__dict__ for p in PRODUCTS])

    return {
        "sales": sales,
        "inventory": inventory,
        "shipments": shipments,
        "service_metrics": service_metrics,
        "market": market_df,
        "products": products_df,
    }


