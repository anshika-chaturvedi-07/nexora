def main() -> None:
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    data = generate()
    for name, df in data.items():
        df.to_csv(RAW_DIR / f"{name}.csv", index=False)
    for fname, text in DOCUMENTS.items():
        (DOCS_DIR / fname).write_text(text, encoding="utf-8")
    summary = {name: len(df) for name, df in data.items()}
    (RAW_DIR / "manifest.json").write_text(json.dumps({"seed": SEED, "start": START, "end": END, "rows": summary}, indent=2))

    s = data["sales"]
    s["date"] = pd.to_datetime(s["date"])
    q = s.groupby(s["date"].dt.to_period("Q"))["revenue"].sum()
    print("rows:", summary)
    print("quarterly revenue (Cr):")
    print((q / 1e7).round(2).to_string())
    print("Q3 vs Q2 2026: {:+.1%}".format(q[pd.Period("2026Q3")] / q[pd.Period("2026Q2")] - 1))


if __name__ == "__main__":
    main()
